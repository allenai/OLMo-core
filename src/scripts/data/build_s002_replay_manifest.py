#!/usr/bin/env python
"""Build finite native-text replay manifests for the s002 vision-alignment run.

This is an offline catalog-to-manifest operation. It only reads already-materialized,
headerless ``uint32`` token files; it never downloads data or launches a job. Source IDs,
labels, remote paths, token counts, and byte digests are not accepted from the materialization
catalog. They are derived from the pinned s002 expanded path manifest, the pinned
``OLMo-mix-0925`` manifest, and a separately reviewed, code-pinned upstream provenance
artifact. The catalog only maps a parent path index to a local materialization.

Windows preserve the parent dataset's exact fixed-length grid: a sequence of length ``L``
reads ``L`` raw IDs, shifts labels within the instance, and ignores the final target. It
therefore contributes ``L - 1`` nominal loss-bearing positions before the parent's repetition
filter is applied.

The source catalog is strict JSON with this shape::

    {
      "format": "olmo_native_text_replay_source_catalog",
      "version": 2,
      "sources": [
        {
          "parent_path_index": 0,
          "path": "tokens/parent-000000.npy"
        }
      ]
    }

The mandatory upstream provenance artifact is not generated by this script. Its reviewed
path and SHA-256 must be set in ``S002_UPSTREAM_PROVENANCE_FILE`` and
``S002_UPSTREAM_PROVENANCE_SHA256``. It binds each parent index and path to its authoritative
token count and full-file SHA-256. Its strict shape is::

    {
      "format": "olmo_native_text_replay_upstream_provenance",
      "version": 1,
      "hash_algorithm": "sha256",
      "parent_paths_sha256": "<pinned expanded-path digest>",
      "parent_mix_sha256": "<pinned labelled-mix digest>",
      "sources": [
        {
          "parent_path_index": 0,
          "parent_path": "s3://ai2-llm/.../000000.npy",
          "num_tokens": 123456789,
          "sha256": "<authoritative full-object digest>"
        }
      ]
    }

The byte inventory must be produced or attested by the upstream data owner, independently of
the local replay materialization. This script fails closed when either code pin is absent.

Catalog paths are local and resolve relative to the catalog. Source proportions are derived
from exact usable window capacity. Repeated ``--*-min-source-tokens SOURCE=TOKENS`` flags
reserve minimum quotas for source labels from the pinned parent mix before the remainder is
apportioned. A normal build streams every source once and emits a pinned verification receipt
beside the manifests; training validates that receipt instead of repeatedly hashing the full
materialized corpus. Receipt version 2 also records the exact bytes of this named builder
implementation, both pinned parent-manifest digests, and the upstream provenance digest. The
builder digest is computed from ``__file__`` when Python loads the module, not embedded as a
fixed value in that same file, so it is reproducible without a self-referential hash.
"""

